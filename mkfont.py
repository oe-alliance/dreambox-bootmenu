"""Render a TTF into 4 bit alpha glyphs for menu.c.

	mkfont.py <font.ttf> <out.h> <name:size> [...]

Covers ASCII and, unless --ascii is given first, Latin-1, Latin Extended-A
and the extra characters of Windows-1252 (euro sign, typographic quotes and
dashes); with --ascii it adds only the middle dot.  The glyphs are sorted by code point, the font carries the list of
code points for a binary search.  Each glyph is stored row by row, two pixels per byte,
high nibble first, rows padded to a full byte.
"""

from sys import argv

from PIL import Image, ImageDraw, ImageFont

ASCII = list(range(0x20, 0x7f))
LATIN1 = list(range(0xa0, 0x100))
LATIN_EXT_A = list(range(0x100, 0x180))
CP1252 = [0x0192, 0x02c6, 0x02dc, 0x2013, 0x2014, 0x2018, 0x2019, 0x201a, 0x201c, 0x201d, 0x201e, 0x2020, 0x2021, 0x2022, 0x2026, 0x2030, 0x2039, 0x203a, 0x20ac, 0x2122]


def render(path, size, codes):
	font = ImageFont.truetype(path, size)
	ascent, descent = font.getmetrics()
	glyphs, bits = [], bytearray()
	for code in codes:
		ch = chr(code)
		adv = round(font.getlength(ch))
		box = font.getbbox(ch)
		w, h = max(0, box[2] - box[0]), max(0, box[3] - box[1])
		if w and h:
			im = Image.new('L', (w, h), 0)
			ImageDraw.Draw(im).text((-box[0], -box[1]), ch, font=font, fill=255)
			px = im.load()
			offset = len(bits)
			for y in range(h):
				for x in range(0, w, 2):
					hi = px[x, y] >> 4
					lo = px[x + 1, y] >> 4 if x + 1 < w else 0
					bits.append(hi << 4 | lo)
		else:
			offset = len(bits)
		# yoff: top of the glyph relative to the top of the line (ascent)
		glyphs.append((w, h, box[0], box[1], adv, offset))
	return ascent, descent, glyphs, bits


def main():
	args = argv[1:]
	codes = ASCII + [0xb7] if args[0] == "--ascii" else sorted(set(ASCII + LATIN1 + LATIN_EXT_A + CP1252))
	if args[0] == "--ascii":
		args = args[1:]
	path, out = args[0], args[1]
	lines = ['/* Generated by mkfont.py from %s (Apache License 2.0, see fonts/LICENSE), do not edit. */' % path.split('/')[-1], '']
	for spec in args[2:]:
		name, size = spec.split(':')
		ascent, descent, glyphs, bits = render(path, int(size), codes)
		lines.append('static const u8 %s_bits[] = {' % name)
		for i in range(0, len(bits), 16):
			lines.append('\t' + ', '.join('0x%02x' % x for x in bits[i:i + 16]) + ',')
		lines.append('};')
		lines.append('static const struct glyph %s_glyphs[] = {' % name)
		for w, h, xoff, yoff, adv, offset in glyphs:
			lines.append('\t{ %d, %d, %d, %d, %d, %d },' % (w, h, xoff, yoff, adv, offset))
		lines.append('};')
		lines.append('static const u16 %s_codes[] = {' % name)
		for i in range(0, len(codes), 12):
			lines.append('\t' + ', '.join('0x%04x' % x for x in codes[i:i + 12]) + ',')
		lines.append('};')
		lines.append('static const struct font %s = { %s_glyphs, %s_bits, %s_codes, %d, %d, %d };' % (name, name, name, name, ascent, ascent + descent, len(glyphs)))
		lines.append('')
	open(out, 'w', newline='\n').write('\n'.join(lines))


if __name__ == '__main__':
	main()
